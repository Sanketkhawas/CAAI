"""
recommendation_validator.py
---------------------------
Validates the output generated by RecommendationEngine.

Responsibilities:
- Validate recommendation structure
- Validate recommendation IDs
- Validate categories
- Validate priorities
- Validate required fields
- Validate recommendation summary
- Validate regime consistency with Tax Engine
- Validate tax-saving evidence
"""

from services.recommendation.recommendation_rules import (
    REGIME_RULES,
    DEDUCTION_RULES,
    INVESTMENT_RULES,
    DATA_RULES,
    PROFILE_VALIDATION_RULES,
    HIGH,
    MEDIUM,
    LOW,
)


class RecommendationValidator:

    VALID_PRIORITIES = {
        HIGH,
        MEDIUM,
        LOW,
    }

    VALID_CONFIDENCE = {
        "High",
        "Medium",
        "Low",
    }

    # ============================================================
    # MAIN VALIDATION
    # ============================================================

    def validate(
        self,
        recommendation_result,
        tax_result=None
    ):
        """
        Validate Recommendation Engine output.

        Returns:
            {
                "valid": bool,
                "errors": list,
                "warnings": list
            }
        """

        errors = []
        warnings = []

        if not isinstance(recommendation_result, dict):
            return {
                "valid": False,
                "errors": [
                    "Recommendation result must be a dictionary."
                ],
                "warnings": [],
            }

        summary = recommendation_result.get("summary")
        recommendations = recommendation_result.get(
            "recommendations"
        )

        # --------------------------------------------------------
        # Basic structure
        # --------------------------------------------------------

        if not isinstance(summary, dict):
            errors.append(
                "Recommendation summary is missing or invalid."
            )

        if not isinstance(recommendations, list):
            errors.append(
                "Recommendations must be a list."
            )

        if errors:
            return {
                "valid": False,
                "errors": errors,
                "warnings": warnings,
            }

        # --------------------------------------------------------
        # Summary validation
        # --------------------------------------------------------

        self.validate_summary(
            summary,
            recommendations,
            errors,
        )

        # --------------------------------------------------------
        # Individual recommendations
        # --------------------------------------------------------

        self.validate_recommendations(
            recommendations,
            errors,
            warnings,
        )

        # --------------------------------------------------------
        # Tax Engine consistency
        # --------------------------------------------------------

        if tax_result:
            self.validate_tax_consistency(
                summary,
                recommendations,
                tax_result,
                errors,
            )

        return {
            "valid": len(errors) == 0,
            "errors": errors,
            "warnings": warnings,
        }

    # ============================================================
    # SUMMARY VALIDATION
    # ============================================================

    def validate_summary(
        self,
        summary,
        recommendations,
        errors
    ):

        required_fields = [
            "recommended_regime",
            "confidence",
            "recommendation_count",
        ]

        for field in required_fields:
            if field not in summary:
                errors.append(
                    f"Summary field '{field}' is missing."
                )

        # --------------------------------------------------------
        # Confidence
        # --------------------------------------------------------

        confidence = summary.get("confidence")

        if confidence not in self.VALID_CONFIDENCE:
            errors.append(
                f"Invalid confidence value: {confidence}"
            )

        # --------------------------------------------------------
        # Recommendation count
        # --------------------------------------------------------

        recommendation_count = summary.get(
            "recommendation_count"
        )

        # bool is a subclass of int in Python, so exclude it.
        if (
            not isinstance(recommendation_count, int)
            or isinstance(recommendation_count, bool)
        ):
            errors.append(
                "recommendation_count must be an integer."
            )

        elif recommendation_count != len(recommendations):
            errors.append(
                "Recommendation count does not match "
                "the number of recommendations."
            )

        # --------------------------------------------------------
        # Recommended regime
        # --------------------------------------------------------

        recommended_regime = summary.get(
            "recommended_regime"
        )

        valid_regimes = {
            "Old Regime",
            "New Regime",
            "Either",
        }

        if recommended_regime not in valid_regimes:
            errors.append(
                f"Invalid recommended regime: "
                f"{recommended_regime}"
            )

    # ============================================================
    # RECOMMENDATION VALIDATION
    # ============================================================

    def validate_recommendations(
        self,
        recommendations,
        errors,
        warnings
    ):

        valid_rule_ids = self.get_valid_rule_ids()

        required_fields = [
            "id",
            "category",
            "title",
            "priority",
            "message",
            "reason",
            "evidence",
        ]

        for index, recommendation in enumerate(
            recommendations,
            start=1
        ):

            prefix = f"Recommendation {index}"

            # ----------------------------------------------------
            # Structure
            # ----------------------------------------------------

            if not isinstance(recommendation, dict):
                errors.append(
                    f"{prefix} must be a dictionary."
                )
                continue

            # ----------------------------------------------------
            # Required fields
            # ----------------------------------------------------

            for field in required_fields:
                if field not in recommendation:
                    errors.append(
                        f"{prefix}: missing field '{field}'."
                    )

            # ----------------------------------------------------
            # ID
            # ----------------------------------------------------

            recommendation_id = recommendation.get("id")

            if recommendation_id not in valid_rule_ids:
                errors.append(
                    f"{prefix}: invalid recommendation "
                    f"ID '{recommendation_id}'."
                )

            # ----------------------------------------------------
            # Priority
            # ----------------------------------------------------

            priority = recommendation.get("priority")

            if priority not in self.VALID_PRIORITIES:
                errors.append(
                    f"{prefix}: invalid priority '{priority}'."
                )

            # ----------------------------------------------------
            # Category
            # ----------------------------------------------------

            category = recommendation.get("category")

            if not category:
                errors.append(
                    f"{prefix}: category cannot be empty."
                )

            # ----------------------------------------------------
            # Title
            # ----------------------------------------------------

            if not recommendation.get("title"):
                errors.append(
                    f"{prefix}: title cannot be empty."
                )

            # ----------------------------------------------------
            # Message
            # ----------------------------------------------------

            if not recommendation.get("message"):
                errors.append(
                    f"{prefix}: message cannot be empty."
                )

            # ----------------------------------------------------
            # Reason
            # ----------------------------------------------------

            if not recommendation.get("reason"):
                errors.append(
                    f"{prefix}: reason cannot be empty."
                )

            # ----------------------------------------------------
            # Evidence
            # ----------------------------------------------------

            evidence = recommendation.get("evidence")

            if not isinstance(evidence, dict):
                errors.append(
                    f"{prefix}: evidence must be a dictionary."
                )

    # ============================================================
    # TAX CONSISTENCY
    # ============================================================

    def validate_tax_consistency(
        self,
        summary,
        recommendations,
        tax_result,
        errors
    ):

        engine_regime = tax_result.get("recommended_regime")
        result_regime = summary.get("recommended_regime")

        # --------------------------------------------------------
        # Regime consistency
        # --------------------------------------------------------

        if engine_regime != result_regime:
            errors.append(
                "Recommended regime does not match "
                "the Tax Engine result."
            )

        # --------------------------------------------------------
        # Find regime recommendation
        # --------------------------------------------------------

        regime_recommendation = None

        for recommendation in recommendations:
            if (
                isinstance(recommendation, dict)
                and recommendation.get("category") == "Tax Regime"
            ):
                regime_recommendation = recommendation
                break

        if not regime_recommendation:
            errors.append(
                "Tax Regime recommendation is missing."
            )
            return

        evidence = regime_recommendation.get("evidence")

        if not isinstance(evidence, dict):
            errors.append(
                "Tax Regime recommendation evidence "
                "must be a dictionary."
            )
            return

        # --------------------------------------------------------
        # Extract Tax Engine values
        # --------------------------------------------------------

        old_regime = tax_result.get("old_regime") or {}
        new_regime = tax_result.get("new_regime") or {}

        if not isinstance(old_regime, dict):
            old_regime = {}

        if not isinstance(new_regime, dict):
            new_regime = {}

        old_tax = self.to_number(
            old_regime.get("total_tax")
        )

        new_tax = self.to_number(
            new_regime.get("total_tax")
        )

        tax_saved = self.to_number(
            tax_result.get("tax_saved")
        )

        evidence_old_tax = self.to_number(
            evidence.get("old_regime_tax")
        )

        evidence_new_tax = self.to_number(
            evidence.get("new_regime_tax")
        )

        evidence_tax_saved = self.to_number(
            evidence.get("tax_saved")
        )

        # --------------------------------------------------------
        # Compare old regime tax
        # --------------------------------------------------------

        if not self.numbers_equal(
            old_tax,
            evidence_old_tax
        ):
            errors.append(
                "Old Regime tax in recommendation "
                "evidence does not match Tax Engine."
            )

        # --------------------------------------------------------
        # Compare new regime tax
        # --------------------------------------------------------

        if not self.numbers_equal(
            new_tax,
            evidence_new_tax
        ):
            errors.append(
                "New Regime tax in recommendation "
                "evidence does not match Tax Engine."
            )

        # --------------------------------------------------------
        # Compare tax saved
        # --------------------------------------------------------

        if not self.numbers_equal(
            tax_saved,
            evidence_tax_saved
        ):
            errors.append(
                "Tax saved in recommendation evidence "
                "does not match Tax Engine."
            )

    # ============================================================
    # VALID RULE IDS
    # ============================================================

    def get_valid_rule_ids(self):

        rule_groups = [
            REGIME_RULES,
            DEDUCTION_RULES,
            INVESTMENT_RULES,
            DATA_RULES,
            PROFILE_VALIDATION_RULES,
        ]

        valid_ids = set()

        for group in rule_groups:
            for rule in group.values():
                rule_id = rule.get("id")

                if isinstance(rule_id, str):
                    valid_ids.add(rule_id)

        return valid_ids

    # ============================================================
    # NUMBER COMPARISON
    # ============================================================

    @staticmethod
    def numbers_equal(
        first,
        second,
        tolerance=0.01
    ):

        if first is None or second is None:
            return False

        return abs(first - second) <= tolerance

    # ============================================================
    # NUMBER CONVERSION
    # ============================================================

    @staticmethod
    def to_number(value):

        if value is None:
            return None

        try:
            return float(value)

        except (ValueError, TypeError):
            return None