"""
recommendation_service.py
-------------------------

Service layer for the CAAI Recommendation System.

Responsibilities:
- Coordinate Recommendation Engine
- Coordinate Recommendation Validator
- Provide a single entry point for Flask/application code
- Return validated recommendation results

The service does NOT:
- calculate taxes
- make tax-regime decisions
- modify financial profile data
"""

from services.recommendation.recommendation_engine import (
    RecommendationEngine
)

from services.recommendation.recommendation_validator import (
    RecommendationValidator
)


class RecommendationService:

    def __init__(
        self,
        recommendation_engine=None,
        recommendation_validator=None
    ):
        """
        Initialize Recommendation Service.

        Optional dependency injection is supported so that
        individual components can be replaced or mocked
        during testing.
        """

        self.engine = (
            recommendation_engine
            if recommendation_engine
            else RecommendationEngine()
        )

        self.validator = (
            recommendation_validator
            if recommendation_validator
            else RecommendationValidator()
        )

    # ============================================================
    # MAIN SERVICE METHOD
    # ============================================================

    def generate_recommendations(
        self,
        financial_profile,
        tax_result,
        validation_result=None
    ):
        """
        Generate and validate recommendations.

        Parameters
        ----------
        financial_profile : dict
            Financial profile generated by FinancialProfileBuilder.

        tax_result : dict
            Result generated by TaxEngine.calculate().

        validation_result : dict, optional
            Result generated by FinancialProfileValidator.

        Returns
        -------
        dict
            Final service response.
        """

        # --------------------------------------------------------
        # STEP 1 : Basic input validation
        # --------------------------------------------------------

        if not isinstance(
            financial_profile,
            dict
        ):
            return self._error_response(
                "Financial profile must be a dictionary."
            )

        if not isinstance(
            tax_result,
            dict
        ):
            return self._error_response(
                "Tax Engine result must be a dictionary."
            )

        if validation_result is not None:

            if not isinstance(
                validation_result,
                dict
            ):
                return self._error_response(
                    "Validation result must be a dictionary."
                )

        # --------------------------------------------------------
        # STEP 2 : Generate recommendations
        # --------------------------------------------------------

        recommendation_result = (
            self.engine.generate(

                financial_profile=
                    financial_profile,

                tax_result=
                    tax_result,

                validation_result=
                    validation_result
            )
        )

        # --------------------------------------------------------
        # STEP 3 : Validate recommendations
        # --------------------------------------------------------

        validator_result = (
            self.validator.validate(

                recommendation_result=
                    recommendation_result,

                tax_result=
                    tax_result
            )
        )

        # --------------------------------------------------------
        # STEP 4 : Handle validation failure
        # --------------------------------------------------------

        if not validator_result["valid"]:

            return {

                "success": False,

                "validated": False,

                "recommendations":
                    recommendation_result,

                "validation":
                    validator_result,

                "errors":
                    validator_result.get(
                        "errors",
                        []
                    ),

                "warnings":
                    validator_result.get(
                        "warnings",
                        []
                    )
            }

        # --------------------------------------------------------
        # STEP 5 : Successful response
        # --------------------------------------------------------

        return {

            "success": True,

            "validated": True,

            "recommendations":
                recommendation_result,

            "validation":
                validator_result,

            "errors": [],

            "warnings":
                validator_result.get(
                    "warnings",
                    []
                )
        }

    # ============================================================
    # SIMPLE ALIAS
    # ============================================================

    def generate(
        self,
        financial_profile,
        tax_result,
        validation_result=None
    ):
        """
        Short alias for generate_recommendations().
        """

        return self.generate_recommendations(

            financial_profile=
                financial_profile,

            tax_result=
                tax_result,

            validation_result=
                validation_result
        )

    # ============================================================
    # ERROR RESPONSE
    # ============================================================

    @staticmethod
    def _error_response(message):
        """
        Create a standardized service-level error response.
        """

        return {

            "success": False,

            "validated": False,

            "recommendations": None,

            "validation": {

                "valid": False,

                "errors": [
                    message
                ],

                "warnings": []
            },

            "errors": [
                message
            ],

            "warnings": []
        }